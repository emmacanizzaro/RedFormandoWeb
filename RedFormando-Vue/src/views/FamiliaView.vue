<script setup>
import '../assets/familia-custom.css'
import { onMounted, onBeforeUnmount } from 'vue'
import { useMeta } from '../plugins/meta.js'
const familiaImg = new URL('/assets/images/Familia.png', import.meta.url).href
let resizeObs = null
function igualarAlturaFoto() {
  const tabla = document.querySelector('.congregaciones-box')
  const foto = document.querySelector('.family-photo-frame')
  if (!tabla || !foto) return
  if (window.innerWidth < 900) {
    foto.style.height = ''
    return
  }
  foto.style.height = tabla.offsetHeight + 'px'
}
useMeta({
  title: 'REDFORMANDO | Familia',
  meta: [
    {
      name: 'description',
      content:
        'Listado de congregaciones, pastores, domicilios, contactos y obreros de la familia RedFormando.',
    },
    { property: 'og:title', content: 'REDFORMANDO | Familia' },
    {
      property: 'og:description',
      content: 'Directorio de congregaciones y obreros de la red ministerial RedFormando.',
    },
    { property: 'og:image', content: 'https://www.redformando.com/assets/images/Redformando.png' },
    { name: 'twitter:title', content: 'REDFORMANDO | Familia' },
    {
      name: 'twitter:description',
      content: 'Listado de congregaciones, pastores y obreros de la familia ministerial.',
    },
    { name: 'twitter:image', content: 'https://www.redformando.com/assets/images/Redformando.png' },
  ],
})

onMounted(() => {
  window.addEventListener('resize', igualarAlturaFoto)
  // Observa cambios en la tabla para igualar altura si cambia el contenido
  const tabla = document.querySelector('.congregaciones-box')
  if (tabla && window.ResizeObserver) {
    resizeObs = new ResizeObserver(igualarAlturaFoto)
    resizeObs.observe(tabla)
  }
})
onBeforeUnmount(() => {
  window.removeEventListener('resize', igualarAlturaFoto)
  if (resizeObs) resizeObs.disconnect()
})
</script>
